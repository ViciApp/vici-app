// Candid, the controller-signed actor, and what each answer means for the run.
// See reassign.ts for the flow.

import { jsonReplacer, nonNullish } from '@dfinity/utils';
import { Actor } from '@icp-sdk/core/agent';
import type { IDL } from '@icp-sdk/core/candid';
import { Principal } from '@icp-sdk/core/principal';
import type { ClearingDid } from '../../src/declarations';
import { env } from '../../src/env';
import { buildAgent } from '../../src/lib/ic-agent';
import { identityFromPemFile } from '../etl/lib';

// ---------------------------------------------------------------------------
// The one clearing method this script calls.
//
// The vendored declarations predate admin_reassign_account and are generated
// files (never hand-edited, regenerated by `npm run did`), so the method's
// Candid lives here, copied from the production clearing's candid:service
// metadata. Decoding fails on a variant tag missing here, so it must list
// every error the canister can answer.

type ReassignAccountError =
	| { AccountNotFound: null }
	| { TargetAccountNotEmpty: null }
	| { CustodyTransferFailed: { error: ClearingDid.AssetError; asset_id: string } }
	| { ReassignmentIdReused: null }
	| { PendingPositionTransfersExist: null }
	| { InFlightPlansExist: null }
	| { UnsupportedCustodyAsset: { asset_id: string } }
	| { AnonymousOwner: null }
	| { ReassignmentInProgress: null }
	| { OpenOrdersExist: null }
	| { SameOwner: null }
	| { Common: ClearingDid.CommonError };

export type ReassignAccountResult = { Ok: null } | { Err: ReassignAccountError };

export interface ReassignAccountParams {
	old_owner: Principal;
	reassignment_id: string;
	new_owner: Principal;
}

/** The controller-side surface, structurally, so tests inject a plain fake. */
export interface ReassignTarget {
	admin_reassign_account: (params: ReassignAccountParams) => Promise<ReassignAccountResult>;
}

export const reassignIdlFactory: IDL.InterfaceFactory = ({ IDL }) => {
	const AssetError = IDL.Variant({
		TransferError: IDL.Text,
		InsufficientBalance: IDL.Record({ balance: IDL.Nat, required: IDL.Nat }),
		MathOverflow: IDL.Null,
		InvalidAssetId: IDL.Text,
		CallError: IDL.Record({ method: IDL.Text, code: IDL.Int32, message: IDL.Text }),
		InvalidAssetForHandler: IDL.Null,
		UnsupportedAsset: IDL.Null
	});
	const CommonError = IDL.Variant({
		Internal: IDL.Text,
		InvalidInput: IDL.Text,
		MathOverflow: IDL.Null,
		Unauthorized: IDL.Null,
		RegistryNotSet: IDL.Null
	});
	const ReassignAccountError = IDL.Variant({
		AccountNotFound: IDL.Null,
		TargetAccountNotEmpty: IDL.Null,
		CustodyTransferFailed: IDL.Record({ error: AssetError, asset_id: IDL.Text }),
		ReassignmentIdReused: IDL.Null,
		PendingPositionTransfersExist: IDL.Null,
		InFlightPlansExist: IDL.Null,
		UnsupportedCustodyAsset: IDL.Record({ asset_id: IDL.Text }),
		AnonymousOwner: IDL.Null,
		ReassignmentInProgress: IDL.Null,
		OpenOrdersExist: IDL.Null,
		SameOwner: IDL.Null,
		Common: CommonError
	});

	return IDL.Service({
		admin_reassign_account: IDL.Func(
			[
				IDL.Record({
					old_owner: IDL.Principal,
					reassignment_id: IDL.Text,
					new_owner: IDL.Principal
				})
			],
			[IDL.Variant({ Ok: IDL.Null, Err: ReassignAccountError })],
			[]
		)
	});
};

/** Fixed per old principal: a re-run resumes or confirms instead of starting
 * a second reassignment. */
export const reassignmentId = (oldPrincipal: string): string => `vici-cutover:${oldPrincipal}`;

// ---------------------------------------------------------------------------
// Outcomes

/** What the operator does about a principal next. */
export type Disposition = 'moved' | 'nothing_to_move' | 'replay' | 'manual' | 'error';

type ErrorKey<T> = T extends T ? keyof T : never;

/** Every error clearing can answer, and what it means for the run: replay
 * (run the script again, the same id resumes), manual (someone has to act
 * first), or an error in the run itself. */
const DISPOSITION_BY_ERROR: Record<ErrorKey<ReassignAccountError>, Disposition> = {
	AccountNotFound: 'nothing_to_move',
	InFlightPlansExist: 'replay',
	ReassignmentInProgress: 'replay',
	CustodyTransferFailed: 'replay',
	TargetAccountNotEmpty: 'manual',
	OpenOrdersExist: 'manual',
	PendingPositionTransfersExist: 'manual',
	UnsupportedCustodyAsset: 'manual',
	// The data disagree with the plan (an earlier run moved this principal to
	// another target, or the link points somewhere it cannot): look first.
	ReassignmentIdReused: 'manual',
	SameOwner: 'manual',
	AnonymousOwner: 'manual',
	Common: 'error'
};

export interface ReassignOutcome {
	kind: string;
	disposition: Disposition;
	detail?: string;
}

export const classifyReassignResult = (result: ReassignAccountResult): ReassignOutcome => {
	if ('Ok' in result) {
		return { kind: 'Ok', disposition: 'moved' };
	}

	const [kind, disposition] =
		Object.entries(DISPOSITION_BY_ERROR).find(([key]) => key in result.Err) ?? [];
	const [payload]: unknown[] = Object.values(result.Err);

	return {
		kind: kind ?? 'unknown',
		disposition: disposition ?? 'error',
		...(nonNullish(payload) && { detail: JSON.stringify(payload, jsonReplacer) })
	};
};

// A controller-gated call refused for the caller: every later call fails the
// same way, so the run stops instead of burning through the list.
export const isUnauthorized = (result: ReassignAccountResult): boolean =>
	'Err' in result && 'Common' in result.Err && 'Unauthorized' in result.Err.Common;

/** The controller-signed surface, from the key at `pemPath`, and the
 * principal that signs. */
export const controllerTarget = async (
	pemPath: string
): Promise<{ target: ReassignTarget; caller: string }> => {
	const identity = identityFromPemFile(pemPath);
	const agent = await buildAgent(identity);

	return {
		target: Actor.createActor<ReassignTarget>(reassignIdlFactory, {
			agent,
			canisterId: Principal.fromText(env.ic.clearingCanisterId)
		}),
		caller: identity.getPrincipal().toText()
	};
};
