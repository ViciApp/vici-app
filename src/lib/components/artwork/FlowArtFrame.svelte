<script lang="ts">
	import { theme } from '#lib/stores/theme.store.ts';
	import {
		flowArtViewBox,
		renderFlowArt,
		type FlowArtCategory,
		type FlowArtState
	} from '#lib/utils/flow-art.utils.ts';

	interface Props {
		// Visual language: a taxonomy macro (folded onto one of the six
		// bespoke render buckets) or the `wc` tentpole editorial variant.
		category: FlowArtCategory;
		// Stable seed: pass `market.id` or any deterministic string /
		// number. Same seed + state always produces the same composition.
		seed: string | number;
		// Resolution state. Flow Mode only ever uses 'neutral'; 'won' /
		// 'lost' are reserved for Portfolio resolution crossfades.
		state?: FlowArtState;
		// Output size in CSS px. Standard scales: 80 (deck thumb),
		// 140 (list card), 220 (hero card on swipe surface).
		size?: number;
		// When true, draws an additional inset stroke frame inside the
		// composition. Off by default; FlowCard layers a separate frame.
		frame?: boolean;
		// When true, the frame fills its container (100% × 100%) instead
		// of rendering at the fixed `size`. Paired with the WC `slice`
		// viewBox this lets the art fill a tall bleed band: cropping
		// horizontally rather than letterboxing in the middle. `size`
		// still drives the SVG's internal resolution.
		fill?: boolean;
		// Optional market question text. Only the WC renderer consults it
		// to look up per-market artwork in the `WC_MARKET_ART` catalogue
		// (then the heuristic resolver); omitting it leaves every render,
		// WC or otherwise, unchanged.
		title?: string;
		// Optional extra class on the wrapper for layout overrides.
		class?: string;
	}

	const {
		category,
		seed,
		state = 'neutral',
		size = 220,
		frame = false,
		fill = false,
		title,
		class: extraClass = ''
	}: Props = $props();

	const svg = $derived(renderFlowArt({ category, seed, state, theme: $theme, size, frame, title }));
	// `wc` renders into a 280×100 viewBox; default categories are 1:1.
	// Mirror that aspect on the host so the SVG isn't squished.
	const viewBox = $derived(flowArtViewBox(category));
	const heightPx = $derived(Math.round((size * viewBox.height) / viewBox.width));
</script>

<div
	style:width={fill ? null : `${size}px`}
	style:height={fill ? null : `${heightPx}px`}
	class="flow-art-frame {extraClass}"
	class:is-fill={fill}
	aria-hidden="true"
>
	<!-- The SVG output is generated by `renderFlowArt` from a fixed palette
	     and numeric coordinates derived from a deterministic seed; no
	     user-controllable input flows into this string. Safe to inline. -->
	<!-- eslint-disable-next-line svelte/no-at-html-tags -->
	{@html svg}
</div>

<style lang="postcss">
	.flow-art-frame {
		display: inline-block;
		line-height: 0;
		border-radius: var(--r-12);
		overflow: hidden;
		box-shadow: var(--inset-hi);
		flex: 0 0 auto;
	}

	/* Fill mode: stretch to the host band instead of the fixed size. */
	.flow-art-frame.is-fill {
		display: block;
		width: 100%;
		height: 100%;
		flex: 1 1 auto;
	}

	.flow-art-frame :global(svg) {
		display: block;
