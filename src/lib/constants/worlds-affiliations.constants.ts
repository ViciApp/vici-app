import type { AffiliationKind } from '#lib/types/affiliation.ts';

/**
 * Static rosters for the FE Worlds picker. The satellite keys
 * affiliations by `(kind, affiliationIdentifier)` without validating against
 * an external list, so the FE owns the curated set of choices.
 *
 * Future: an admin-curated registry collection can replace these
 * hardcoded arrays without touching the satellite assert (the assert
 * only enforces shape + lock, not the affiliation id's existence).
 */

export interface WorldsAffiliationOption {
	/** External id stored on `AffiliationDoc.affiliationIdentifier`. */
	id: string;
	/** Display name. */
	name: string;
	/** Decorative glyph: emoji flag for countries, short acronym for
	 *  universities (mirrors {@link short} for the university roster so
	 *  every existing consumer keeps rendering a tile). */
	glyph: string;
	/** University-only fields below: countries never carry them. */
	/** Short acronym shown on the picker tile. */
	short?: string;
	/** ISO-3166-1 alpha-2 home country, drives the picker's "Near you"
	 *  pinning. */
	country?: string;
	/** Coarse region bucket backing the picker's region tabs. `LATAM`
	 *  and `MEA` entries surface only under the "All" tab or search. */
	region?: 'NA' | 'UK' | 'EU' | 'AS' | 'AU' | 'LATAM' | 'MEA';
	/** Verified email domains: reserved for a later membership-
	 *  verification pass; unused by the current picker. */
	domains?: readonly string[];
	/** Approximate QS World Rank, used as the default browse sort. */
	rank?: number;
	/** Brand colour for the tile background (hex). */
	color?: string;
	/** Foreground colour over {@link color} (hex). */
	text?: string;
}

