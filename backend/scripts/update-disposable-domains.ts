// Regenerates src/waitlist/disposable-domains.txt, the disposable-mail
// domains the waitlist refuses, from the community list published as
// disposable-email-domains (CC0). Run by hand or by the monthly workflow
// (.github/workflows/update-disposable-domains.yml), which opens a pull
// request when the file changed, so every update is reviewed like code.
//
//   bun run scripts/update-disposable-domains.ts

import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

const UPSTREAM_URL =
	'https://raw.githubusercontent.com/disposable-email-domains/disposable-email-domains/main/disposable_email_blocklist.conf';

const OUTPUT_FILE = join(import.meta.dir, '..', 'src', 'waitlist', 'disposable-domains.txt');

// The upstream list holds thousands of domains; far fewer means a broken
// fetch, and writing it would quietly open the waitlist to throwaway inboxes.
const MIN_EXPECTED_DOMAINS = 1000;

const FETCH_TIMEOUT_MS = 30_000;

const DOMAIN_RE = /^[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)+$/;

const HEADER = [
	'# Disposable-mail domains the waitlist refuses, one per line.',
	'# Generated by scripts/update-disposable-domains.ts from the community list',
	'# published as disposable-email-domains; do not edit by hand. Block or exempt',
	'# a domain at once through the app setting waitlist_email_domains instead.'
];

const response = await fetch(UPSTREAM_URL, { signal: AbortSignal.timeout(FETCH_TIMEOUT_MS) });

if (!response.ok) {
	throw new Error(`upstream answered ${response.status}`);
}

const domains = [
	...new Set(
		(await response.text())
			.split('\n')
			.map((line) => line.trim().toLowerCase())
			.filter((line) => DOMAIN_RE.test(line))
	)
].sort();

if (domains.length < MIN_EXPECTED_DOMAINS) {
	throw new Error(`only ${domains.length} domains upstream; refusing to write the list`);
}

writeFileSync(OUTPUT_FILE, [...HEADER, ...domains, ''].join('\n'));
console.log(`wrote ${domains.length} domains to ${OUTPUT_FILE}`);
