/**
 * Normalizes a market question into the key both the schedule table and the
 * lookups are indexed by: trimmed, internal whitespace collapsed to single
 * spaces, lower-cased. Accents and apostrophes are intentionally preserved —
 * they are part of the team names that distinguish questions. Both the table
 * (build time) and incoming market titles (lookup time) pass through this so
 * a match never hinges on incidental spacing or casing differences.
 */
export const normalizeWcQuestion = (question: string): string =>
	question.trim().replace(/\s+/g, ' ').toLowerCase();

/**
 * Builds the `normalized question -> earliest reveal (ms, 00:00 UTC of the
 * Show Date)` lookup from {@link WC_MARKET_SCHEDULE}. A question listed under
 * more than one date resolves to its earliest release, so a market is never
 * held back past the first day it was scheduled to appear.
 *
 * The **first** scheduled day is seeded as always-on (reveal `0`) so the WC
 * feed is never empty before the calendar formally begins — the opening set
 * is live the moment this ships, and every later set still unlocks at 00:00
 * UTC of its own Show Date. Once the opening day is in the past this clamp is
 * a no-op (its real timestamp would already be revealed), so it only bridges
 * the pre-launch gap and never leaks a future day into the current one.
 */
const buildRevealMap = (): ReadonlyMap<string, number> => {
	const map = new Map<string, number>();

	// Object key order is insertion order: the calendar is authored
	// chronologically, so the first date is the opening set we seed as live.
	const [openingDate] = Object.keys(WC_MARKET_SCHEDULE);

	for (const [showDate, questions] of Object.entries(WC_MARKET_SCHEDULE)) {
		// This calendar is hand-edited, so a typo'd Show Date would otherwise
		// parse to `NaN` and silently hide its whole set forever. Fail loud at
		// module load (dev/CI) instead so the mistake is caught immediately.
		const parsedMs = Date.parse(`${showDate}T00:00:00.000Z`);

		if (Number.isNaN(parsedMs)) {
			throw new Error(
				`Invalid WC schedule Show Date "${showDate}" — expected an ISO YYYY-MM-DD key.`
			);
		}

		const revealMs = showDate === openingDate ? 0 : parsedMs;

		for (const question of questions) {
			const key = normalizeWcQuestion(question);
			const existing = map.get(key);

			if (isNullish(existing) || revealMs < existing) {
				map.set(key, revealMs);
			}
		}
	}

	return map;
};

/**
 * `normalized question -> reveal timestamp (ms)` for every scheduled
 * World-Cup market. A missing key means the market is not on the calendar
 * and must stay hidden.
 */
export const WC_QUESTION_REVEAL_MS: ReadonlyMap<string, number> = buildRevealMap();
