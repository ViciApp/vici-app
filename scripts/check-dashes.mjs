#!/usr/bin/env node
/**
 * Rule 14 of the code standard: no em dash (U+2014) anywhere, and no en dash
 * (U+2013) used the same way, as a break with whitespace on both sides. An en
 * dash between two values with no spaces is a range and stays (`10–20`).
 *
 * Scans every file git knows (tracked, or new and not ignored) that reads as
 * UTF-8 text, and exits non-zero with `path:line` for each hit. Wired into
 * `npm run check:dashes` and `npm run lint`.
 *
 * The exceptions below are files this repository does not write by hand; each
 * carries its reason. See `docs/ai/pr-and-ci.md`.
 */
import { isNullish } from '@dfinity/utils';
import { execFileSync } from 'node:child_process';
import { readFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

const DASH = new RegExp('\\u2014|\\s\\u2013\\s');

const SUBDIRS = 'subdirectories only';

/** Path prefixes or exact paths left alone, each with its reason. */
const EXCEPTIONS = [
	['CHANGELOG.md', 'written by release-please from past commit titles'],
	['src/declarations/', 'generated bindings, comments copied from icdc-core Candid', SUBDIRS],
	['backend/src/declarations/', 'vendored copy of the generated bindings', SUBDIRS],
	['src/satellite/satellite.did', 'generated by juno functions build'],
	['src/satellite/satellite_extension.did', 'generated by juno functions build'],
	['src/satellite/api-schemas.ts', 'generated by juno functions build'],
	['package-lock.json', 'generated by npm'],
	['backend/bun.lock', 'generated by bun']
];

/**
 * A `dir/` entry covers everything under it; with SUBDIRS it covers only the
 * folders inside it, so the hand-written wiring files at its root stay checked.
 */
const matches = ({ entry, scope, file }) => {
	if (!entry.endsWith('/')) {
		return file === entry;
	}

	if (!file.startsWith(entry)) {
		return false;
	}

	return scope !== SUBDIRS || file.slice(entry.length).includes('/');
};

const excepted = (file) => EXCEPTIONS.some(([entry, , scope]) => matches({ entry, scope, file }));

const files = execFileSync(
	'git',
	['ls-files', '-z', '--cached', '--others', '--exclude-standard'],
	{
		cwd: root,
		encoding: 'utf8'
	}
)
	.split('\0')
	.filter((file) => file !== '' && !excepted(file));

const decoder = new TextDecoder('utf-8', { fatal: true });

const readText = (file) => {
	try {
		return decoder.decode(readFileSync(path.join(root, file)));
	} catch {
		// Binary or not UTF-8 (images, fonts) or deleted in the working tree:
		// nothing to check.
	}
};

const problems = files.flatMap((file) => {
	const text = readText(file);

	if (isNullish(text)) {
		return [];
	}

	return text
		.split('\n')
		.flatMap((line, index) => (DASH.test(line) ? [`${file}:${index + 1}`] : []));
});

if (problems.length > 0) {
	console.error(
		`✗ ${problems.length} line(s) with an em dash, or an en dash between spaces (code standard rule 14):`
	);
	problems.forEach((problem) => console.error(`  ${problem}`));
	console.error(
		'Use a comma, a colon, parentheses or two sentences; keep en dashes only in ranges like 10–20.'
	);
	process.exit(1);
}

console.log(`✓ no em dash or spaced en dash across ${files.length} files`);
